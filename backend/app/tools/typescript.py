"""The frontend's tool result types (frontend/src/toolResults.ts), written from the tools' declared result models.

One source for each shape: the pydantic model the backend checks every result against (app.tools.registry). The
types come from the models' JSON schemas, so they say what the check enforces: `X | null` for a value that may be
None, `field?: X` for one that's absent when unset. A test fails when the committed file is out of date.

Run from backend/: `uv run python -m app.tools.typescript`.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[3] / "frontend" / "src" / "toolResults.ts"

HEADER = """\
// Generated by `uv run python -m app.tools.typescript` (backend/) from the tools' declared result models.
// Don't edit by hand: change the model in backend/app/tools/, then run the command again.
"""

FOOTER = """\
export type ToolName = keyof ToolResults

/** A tool call's name and result together: check the name, and the result has that tool's type. An unknown tool's
 *  call never has a result. */
export type NamedResult =
  | { [K in ToolName]: { name: K; result: ToolResults[K] | null } }[ToolName]
  | { name: string; result: null }
"""

SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _type(s: dict, refs: list[str]) -> str:
    """One JSON schema as a TypeScript type. Each model it names is added to `refs`."""
    if "$ref" in s:
        refs.append(_ref_name(s["$ref"]))
        return _ref_name(s["$ref"])
    if "allOf" in s and len(s["allOf"]) == 1:
        return _type(s["allOf"][0], refs)
    if "anyOf" in s or "oneOf" in s:
        return " | ".join(_type(x, refs) for x in s.get("anyOf") or s["oneOf"])
    if "const" in s:
        return repr(s["const"]) if isinstance(s["const"], str) else str(s["const"]).lower()
    if "enum" in s:
        return " | ".join(f"'{v}'" for v in s["enum"])
    if s.get("type") == "array":
        item = _type(s["items"], refs)
        return f"({item})[]" if " | " in item else f"{item}[]"
    if s.get("type") == "object" and "properties" not in s:
        return f"Record<string, {_type(s.get('additionalProperties') or {}, refs)}>"
    if s.get("type") in SCALARS:
        return SCALARS[s["type"]]
    raise ValueError(f"no TypeScript type for {s}")


def _interface(name: str, s: dict, refs: list[str]) -> str:
    lines = [f"/** {s['description']} */"] if s.get("description") else []
    lines.append(f"export interface {name} {{")
    required = set(s.get("required", ()))
    for field, fs in s["properties"].items():
        lines.append(f"  {field}{'' if field in required else '?'}: {_type(fs, refs)}")
    return "\n".join([*lines, "}"])


def typescript(specs: dict) -> str:
    """The module for these tool specs (name -> ToolSpec): every model their results use, then the ToolResults map."""
    done: dict[str, dict] = {}  # model name -> its schema, so two different models can't share a name
    blocks, results = [], []
    for name, spec in specs.items():
        schema = spec.results.json_schema(ref_template="#/$defs/{model}")
        defs = dict(schema.get("$defs", {}))
        if "properties" in schema:  # one model: the schema is the model itself
            defs[schema["title"]] = {k: v for k, v in schema.items() if k != "$defs"}
            schema = {"$ref": f"#/$defs/{schema['title']}"}
        todo: list[str] = []
        results.append(f"  {name}: {_type(schema, todo)}")
        while todo:
            model = todo.pop(0)
            if model in done:
                if done[model] != defs[model]:
                    raise ValueError(f"two different result models are called {model}")
                continue
            done[model] = defs[model]
            refs: list[str] = []
            blocks.append(_interface(model, defs[model], refs))
            todo += refs
    tools = "\n".join(["/** Each tool's result, by the tool's name. */", "export interface ToolResults {", *results, "}"])
    return "\n\n".join([HEADER.rstrip("\n").replace("\n\n", "\n"), *blocks, tools, FOOTER.rstrip("\n")]) + "\n"


if __name__ == "__main__":
    from app.tools.registry import TOOLS

    OUT.write_text(typescript(TOOLS))
    print(f"Wrote {OUT}")
