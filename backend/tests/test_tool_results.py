"""Declared tool result shapes (architecture review, candidate 6): every tool's result is checked against its model."""
from typing import Literal

import pytest
from pydantic import BaseModel

from app import guard
from app.llm.base import ToolCall
from app.llm.fake import FakeLLM
from app.tools import registry
from app.tools.registry import TOOLS, Context, ToolResult, ToolSpec, run_tool


class NoArgs(BaseModel):
    pass


class Shape(ToolResult):
    message: str
    count: int


class Inner(ToolResult):
    code: str


class Toy(ToolResult):
    """A toy result."""
    kind: Literal["a", "b"]
    one: Literal["only"]
    note: str | None
    inner: Inner | None
    items: list[Inner]
    counts: dict[str, int]
    score: float
    flag: bool
    maybe: str = None  # type: ignore[assignment]  # absent when there's nothing to say


class Other(ToolResult):
    kind: Literal["c"]


TOY = """\
// Generated by `uv run python -m app.tools.typescript` (backend/) from the tools' declared result models.
// Don't edit by hand: change the model in backend/app/tools/, then run the command again.

/** A toy result. */
export interface Toy {
  kind: 'a' | 'b'
  one: 'only'
  note: string | null
  inner: Inner | null
  items: Inner[]
  counts: Record<string, number>
  score: number
  flag: boolean
  maybe?: string
}

export interface Inner {
  code: string
}

export interface Other {
  kind: 'c'
}

/** Each tool's result, by the tool's name. */
export interface ToolResults {
  toy: Toy
  either: Toy | Other
}

export type ToolName = keyof ToolResults

/** A tool call's name and result together: check the name, and the result has that tool's type. An unknown tool's
 *  call never has a result. */
export type NamedResult =
  | { [K in ToolName]: { name: K; result: ToolResults[K] | null } }[ToolName]
  | { name: string; result: null }
"""


def test_the_typescript_types_follow_the_result_models():
    from app.tools.typescript import typescript

    def spec(name, result):
        return ToolSpec(name=name, description="", args_model=NoArgs, result=result, run=lambda *a: None)

    assert typescript({"toy": spec("toy", Toy), "either": spec("either", Toy | Other)}) == TOY


def test_the_frontend_tool_result_types_are_up_to_date():
    """frontend/src/toolResults.ts is written from the models: after changing one, run the generator again."""
    from app.tools.typescript import OUT, typescript

    assert OUT.read_text() == typescript(TOOLS), "run `uv run python -m app.tools.typescript` in backend/"


@pytest.fixture
def drifting_tool():
    """A tool whose result doesn't match its declared model: `returns` sets what it returns."""
    spec = ToolSpec(name="drifting", description="test", args_model=NoArgs, result=Shape,
                    run=lambda args, deps, ctx: spec.returns)
    registry.register(spec)
    yield spec
    del TOOLS["drifting"]


def run(spec, returns):
    spec.returns = returns
    return run_tool(ToolCall(id="t", name=spec.name, args={}), None, Context())


def test_a_result_that_matches_its_model_is_returned_as_is(drifting_tool):
    rec = run(drifting_tool, {"message": "hi", "count": 2})
    assert rec.status == "ok" and rec.result == {"message": "hi", "count": 2}


@pytest.mark.parametrize("returns", [
    {"message": "hi"},  # a key went missing
    {"message": "hi", "count": 2, "extra": True},  # a key nobody declared
    {"message": "hi", "count": "two"},  # a value of the wrong type
])
def test_a_drifting_result_shape_is_a_tool_failure(drifting_tool, returns):
    rec = run(drifting_tool, returns)
    assert rec.status == "error" and rec.result is None
    assert rec.error["code"] == "tool_failed"


# FakeLLM picks its reply template by the tool's name, never by which keys a result happens to have.

def _conversation(steps: list[tuple[str, dict]]) -> list[dict]:
    """The messages after an unscripted CVE question: one assistant step per (tool name, result)."""
    msgs = [{"role": "system", "content": "Explain level: normal."},
            {"role": "user", "content": "Tell me about CVE-2025-3248"}]
    for i, (name, result) in enumerate(steps):
        msgs.append({"role": "assistant", "content": None, "tool_calls": [
            {"id": f"call_{i}_0", "type": "function", "function": {"name": name, "arguments": "{}"}}]})
        msgs.append({"role": "tool", "tool_call_id": f"call_{i}_0", "content": guard.wrap_untrusted(name, result)})
    return msgs


def _result(deps, name, **args):
    return run_tool(ToolCall(id="t", name=name, args=args), deps, Context()).result


@pytest.mark.parametrize("extra", [{"total_open": 3}, {"counts": {}}, {"sources": []}, {"kind": "cwe"}])
def test_fake_llm_answers_a_lookup_by_its_tool_name_whatever_extra_keys_it_has(deps, extra):
    cve = _result(deps, "lookup_cve", cve_id="CVE-2025-3248")
    found = _result(deps, "search_security", query="How to prevent Injection")
    plain = FakeLLM().step(_conversation([("lookup_cve", cve), ("search_security", found)]), [])
    drifted = FakeLLM().step(_conversation([("lookup_cve", cve | extra), ("search_security", found)]), [])
    assert plain.content.startswith("**CVE-2025-3248** in Langflow")
    assert drifted.content == plain.content


def test_fake_llm_searches_after_a_lookup_by_its_tool_name(deps):
    """The unscripted CVE question's second step (search how to prevent its kind of bug) follows lookup_cve only.
    check_affected's one-CVE result also has a watch_status, and gets its verdict line, not a search."""
    cve = _result(deps, "lookup_cve", cve_id="CVE-2025-3248")
    reply = FakeLLM().step(_conversation([("lookup_cve", cve)]), [])
    assert [(c.name, c.args) for c in reply.tool_calls] == [("search_security", {"query": "How to prevent Injection"})]
    verdict = _result(deps, "check_affected", cve_id="CVE-2025-3248")
    reply = FakeLLM().step(_conversation([("check_affected", verdict)]), [])
    assert not reply.tool_calls and reply.content.startswith("**CVE-2025-3248** in Langflow [1]: **")
    failed = {"error": {"code": "cve_not_in_snapshot", "message": "CVE-2025-3248 isn't in my snapshot."}}
    reply = FakeLLM().step(_conversation([("lookup_cve", failed)]), [])
    assert not reply.tool_calls and reply.content == "CVE-2025-3248 isn't in my snapshot."

